"""Elige dónde calcular: GPU de Nvidia (Colab), GPU del chip Apple (Mac) o procesador."""


def pick_device() -> str:
    try:
        import torch
    except ImportError:
        return "cpu"
    if torch.cuda.is_available():
        return "cuda"
    if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
        return "mps"
    return "cpu"
